# ---- الحلقة الذكية: حلقة حول الأيقونة تعرض نسبة (تمتلئ عند الفتح) ----
import itertools as _it

_uid = _it.count(1)
_GOLD = "#D4A53F"


def status_color(pct) -> str:
    """لون الحالة: أخضر ٨٠٪ فأكثر، كهرماني ٥٠–٧٩٪، أحمر أقل من ذلك."""
    p = float(pct or 0)
    return "#1E9E6A" if p >= 80 else "#E0A12B" if p >= 50 else "#E5484D"


def _pct(v) -> int:
    try:
        return max(0, min(100, int(round(float(v)))))
    except (TypeError, ValueError):
        return 100


def ring(name, pct=None, color="#13795B", cls="", badge=None, glyph=None) -> Markup:
    """أيقونة داخل حلقة بنسبة ``pct`` (بلا نسبة = حلقة كاملة).

    ``glyph="gold"`` يرسم الأيقونة بتدرّج أبيض←ذهبي (للقائمة الداكنة)،
    وإلا فبلون ``glyph`` أو ``color``. ``badge`` = ``{"n": 3, "level": "danger"}``."""
    key = EMOJI.get(str(name).replace("️", ""), name)
    body = ICONS.get(key, "")
    n = next(_uid)
    p = 100 if pct is None else _pct(pct)
    if glyph == "gold":
        gdef = (f'<defs><linearGradient id="rg{n}g" gradientUnits="userSpaceOnUse" x1="2" y1="2" '
                f'x2="22" y2="22"><stop offset="0" stop-color="#fff"/><stop offset="1" '
                f'stop-color="#F2D58A"/></linearGradient></defs>')
        gstyle = f"stroke:url(#rg{n}g)"
    else:
        gdef, gstyle = "", f"stroke:{escape(glyph or color)}"
    b = ""
    if badge and badge.get("n"):
        b = (f'<span class="ring-badge {escape(badge.get("level", ""))}">'
             f'{escape(badge["n"])}</span>')
    c = escape(color)
    return Markup(
        f'<span class="ring {escape(cls)}" style="--rc:{c}">'
        f'<svg class="ring-svg" viewBox="0 0 40 40" aria-hidden="true"><defs>'
        f'<linearGradient id="rg{n}" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="{c}"/>'
        f'<stop offset="1" stop-color="{_GOLD}"/></linearGradient></defs>'
        f'<circle class="ring-disc" cx="20" cy="20" r="17"/>'
        f'<circle class="ring-track" cx="20" cy="20" r="17"/>'
        f'<circle class="ring-arc" cx="20" cy="20" r="17" pathLength="100" stroke="url(#rg{n})" '
        f'style="stroke-dasharray:{p} 100" transform="rotate(-90 20 20)"/></svg>'
        f'<svg class="ico ring-g" viewBox="0 0 24 24" aria-hidden="true" style="{gstyle}">'
        f'{gdef}{body}</svg>{b}</span>')


def rings(items) -> Markup:
    """حلقات متداخلة (بأسلوب حلقات النشاط): ``[(النسبة، اللون)]`` من الخارج للداخل."""
    parts, defs = [], []
    for (pct, color), r in zip(items, (18, 13.4, 8.8)):
        n = next(_uid)
        c = escape(color)
        defs.append(f'<linearGradient id="rg{n}" x1="0" y1="0" x2="1" y2="1">'
                    f'<stop offset="0" stop-color="{c}"/><stop offset="1" stop-color="{_GOLD}"/>'
                    f'</linearGradient>')
        parts.append(f'<circle class="ring-track" cx="20" cy="20" r="{r}" style="stroke:{c}"/>'
                     f'<circle class="ring-arc" cx="20" cy="20" r="{r}" pathLength="100" '
                     f'stroke="url(#rg{n})" style="stroke-dasharray:{_pct(pct)} 100" '
                     f'transform="rotate(-90 20 20)"/>')
    return Markup(f'<svg class="rings-svg" viewBox="0 0 40 40" aria-hidden="true">'
                  f'<defs>{"".join(defs)}</defs>{"".join(parts)}</svg>')


_base_install = install


def install(app) -> None:  # noqa: F811
    _base_install(app)
    app.jinja_env.globals.update(ring=ring, rings=rings, status_color=status_color)
