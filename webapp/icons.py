_EMOJI_RE = re.compile("(" + "|".join(sorted(map(re.escape, EMOJI), key=len,
                                                reverse=True)) + ")️?")


def svg(name: str, cls: str = "") -> Markup:
    body = ICONS.get(name)
    if body is None:
        return Markup("")
    extra = f" {cls}" if cls else ""
    return Markup(f'<svg class="ico{extra}" viewBox="0 0 24 24" aria-hidden="true">'
                  f'{body}</svg>')


def ic(key: str, cls: str = "") -> Markup:
    """أيقونة باسمها أو بالإيموجي المقابل؛ الإيموجي غير المعروف يُعاد نصّاً."""
    key = str(key or "").replace("️", "").strip()
    if key in ICONS:
        return svg(key, cls)
    if key in EMOJI:
        return svg(EMOJI[key], cls)
    return escape(key)


def iconize(text) -> Markup:
    """يهرّب النص ثم يحوّل الإيموجي المعروفة فيه إلى أيقونات."""
    safe = str(escape("" if text is None else text))
    return Markup(_EMOJI_RE.sub(lambda m: str(svg(EMOJI[m.group(1)])), safe))


def install(app) -> None:
    app.jinja_env.globals["ic"] = ic
    app.jinja_env.filters["iconize"] = iconize


