_KEYS = [date.fromisoformat(s) for s, _y, _m in _STARTS]
_LAST = date(2035, 1, 11)                  # نهاية آخر شهر في الجدول (شوّال 1456)


def _tabular(d: date) -> tuple:
    """التقويم الهجري الحسابي (خارج جدول أمّ القرى)."""
    jd = d.toordinal() + 1721424.5
    epoch = 1948439.5

    def to_jd(y, m, dd=1):
        return dd + math.ceil(29.5 * (m - 1)) + (y - 1) * 354 + (3 + 11 * y) // 30 + epoch - 1
    y = int((30 * (jd - epoch) + 10646) // 10631)
    m = min(12, math.ceil((jd - (29 + to_jd(y, 1))) / 29.5) + 1)
    return y, m, int(jd - to_jd(y, m) + 1)


def to_hijri(d: date) -> tuple:
    """(السنة، الشهر، اليوم) الهجري لتاريخ ميلادي."""
    if _KEYS[0] <= d < _LAST:
        i = bisect_right(_KEYS, d) - 1
        _s, y, m = _STARTS[i]
        return y, m, (d - _KEYS[i]).days + 1
    return _tabular(d)


def to_greg(y: int, m: int, day: int = 1):
    """التاريخ الميلادي لتاريخ هجري (من الجدول؛ None خارجه)."""
    for k, (_s, yy, mm) in zip(_KEYS, _STARTS):
        if yy == y and mm == m:
            return k + timedelta(days=day - 1)
    return None


def fmt(d: date, with_year: bool = True) -> str:
    y, m, day = to_hijri(d)
    return f"{day} {MONTHS[m - 1]}" + (f" {y} هـ" if with_year else "")


def month_year(d: date) -> str:
    y, m, _d = to_hijri(d)
    return f"{MONTHS[m - 1]} {y} هـ"


def is_ramadan(d: date) -> bool:
    return to_hijri(d)[1] == 9


# مناسبات بطاقات التهنئة: (المفتاح، الاسم، الشهر، اليوم، تظهر قبلها بأيام، وتبقى بعدها بأيام)
OCCASIONS = (
    ("ramadan", "شهر رمضان", 9, 1, 6, 10),
    ("fitr", "عيد الفطر", 10, 1, 4, 3),
    ("arafah", "يوم عرفة", 12, 9, 3, 0),
    ("adha", "عيد الأضحى", 12, 10, 3, 3),
    ("newyear", "رأس السنة الهجرية", 1, 1, 4, 2),
)


def occasions(today: date) -> list:
    """المناسبات القادمة (أو الجارية الآن) مرتّبةً بالأقرب — لكلٍّ تاريخه ونافذة عرضه
    في لوحة التحكم و«الآن» إن كان اليوم داخلها."""
    y0 = to_hijri(today)[0]
    out = []
    for key, name, m, day, before, after in OCCASIONS:
        for y in (y0 - 1, y0, y0 + 1):
            g = to_greg(y, m, day)
            if g is None:
                continue
            start, end = g - timedelta(days=before), g + timedelta(days=after)
            if end < today:
                continue
            out.append({"key": key, "name": name, "date": g, "hy": y, "start": start, "end": end,
                        "now": start <= today <= end, "days": (g - today).days})
            break
    out.sort(key=lambda o: o["date"])
    return out
